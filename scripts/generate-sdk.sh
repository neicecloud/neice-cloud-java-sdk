#!/usr/bin/env bash

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEFAULT_SPEC="$ROOT_DIR/api/api.json"
DEFAULT_CONFIG="$ROOT_DIR/api/java.json"
MODERN_SPEC="$ROOT_DIR/api/api.json"
MODERN_CONFIG="$ROOT_DIR/api/java.json"
MODERN_GENERATOR_VERSION="7.7.0"

MODE="${MODE:-compat}"
if [[ "${1:-}" == "--modern" ]]; then
  MODE="modern"
  shift
fi

SPEC_PATH="${1:-$DEFAULT_SPEC}"
CONFIG_PATH="${2:-$DEFAULT_CONFIG}"
GENERATOR_NAME="${GENERATOR_NAME:-java}"
OPENAPI_GENERATOR_VERSION="${OPENAPI_GENERATOR_VERSION:-5.4.0}"
TOOLS_DIR="$ROOT_DIR/.tools"
OPENAPI_GENERATOR_JAR="$TOOLS_DIR/openapi-generator-cli-${OPENAPI_GENERATOR_VERSION}.jar"
CLEAN_REGEN="${CLEAN_REGEN:-true}"
COMPAT_RESTORE_MISSING_FROM_HEAD="${COMPAT_RESTORE_MISSING_FROM_HEAD:-true}"

if [[ "$MODE" == "modern" ]]; then
  SPEC_PATH="$MODERN_SPEC"
  CONFIG_PATH="$MODERN_CONFIG"
  OPENAPI_GENERATOR_VERSION="$MODERN_GENERATOR_VERSION"
  OPENAPI_GENERATOR_JAR="$TOOLS_DIR/openapi-generator-cli-${OPENAPI_GENERATOR_VERSION}.jar"
fi

TEMP_DIR="$(mktemp -d)"
OUTPUT_DIR="$TEMP_DIR/generated"
trap 'rm -rf "$TEMP_DIR"' EXIT

if [[ ! -f "$SPEC_PATH" ]]; then
  echo "Spec file not found: $SPEC_PATH" >&2
  exit 1
fi

if [[ ! -f "$CONFIG_PATH" ]]; then
  echo "Config file not found: $CONFIG_PATH" >&2
  exit 1
fi

# OpenAPI Generator 5.x has limited OpenAPI 3.1 support.
# Keep source file untouched: patch only a temp copy for compatibility.
if [[ "$OPENAPI_GENERATOR_VERSION" == 5.* ]]; then
  if rg -n "\"openapi\"\\s*:\\s*\"3\\.1\\.[0-9]+\"" "$SPEC_PATH" >/dev/null 2>&1; then
    SPEC_5X_COMPAT="$TEMP_DIR/spec-compat-5x.json"
    cp "$SPEC_PATH" "$SPEC_5X_COMPAT"
    python3 - <<'PY' "$SPEC_5X_COMPAT"
import re
import sys
path = sys.argv[1]
with open(path, "r", encoding="utf-8") as f:
    text = f.read()
text = re.sub(r'"openapi"\s*:\s*"3\.1\.[0-9]+"', '"openapi": "3.0.1"', text, count=1)
with open(path, "w", encoding="utf-8") as f:
    f.write(text)
PY
    SPEC_PATH="$SPEC_5X_COMPAT"
  fi
fi

generate_with_openapi_cli() {
  openapi-generator-cli generate \
    --skip-validate-spec \
    -g "$GENERATOR_NAME" \
    -i "$SPEC_PATH" \
    -c "$CONFIG_PATH" \
    -o "$OUTPUT_DIR"
}

generate_with_openapi_jar() {
  java -jar "$OPENAPI_GENERATOR_JAR" generate \
    --skip-validate-spec \
    -g "$GENERATOR_NAME" \
    -i "$SPEC_PATH" \
    -c "$CONFIG_PATH" \
    -o "$OUTPUT_DIR"
}

install_openapi_generator_jar() {
  mkdir -p "$TOOLS_DIR"
  local jar_url="https://repo1.maven.org/maven2/org/openapitools/openapi-generator-cli/${OPENAPI_GENERATOR_VERSION}/openapi-generator-cli-${OPENAPI_GENERATOR_VERSION}.jar"

  if command -v curl >/dev/null 2>&1; then
    curl -fL "$jar_url" -o "$OPENAPI_GENERATOR_JAR"
  elif command -v wget >/dev/null 2>&1; then
    wget -O "$OPENAPI_GENERATOR_JAR" "$jar_url"
  else
    echo "Missing downloader: install curl or wget." >&2
    exit 1
  fi
}

echo "Generating SDK from: $SPEC_PATH"
echo "Using config: $CONFIG_PATH"

if command -v openapi-generator-cli >/dev/null 2>&1; then
  echo "Toolchain: openapi-generator-cli"
  generate_with_openapi_cli
else
  if [[ ! -f "$OPENAPI_GENERATOR_JAR" ]]; then
    echo "Toolchain: openapi-generator jar (auto-install ${OPENAPI_GENERATOR_VERSION})"
    install_openapi_generator_jar
  else
    echo "Toolchain: openapi-generator jar ($OPENAPI_GENERATOR_VERSION)"
  fi

  if ! command -v java >/dev/null 2>&1; then
    echo "Java is required to run openapi-generator-cli jar." >&2
    exit 1
  fi

  generate_with_openapi_jar
fi

NEW_FILES_MANIFEST="$OUTPUT_DIR/.openapi-generator/FILES"
OLD_FILES_MANIFEST="$ROOT_DIR/.openapi-generator/FILES"
MISSING_RESTORE_LIST="$TEMP_DIR/missing-restore-from-head.txt"

should_skip_generated_path() {
  local rel_path="$1"
  case "$rel_path" in
    "docs/.md"|"src/main/java/cloud/neice/model/.java"|"src/test/java/cloud/neice/model/Test.java")
      return 0
      ;;
    *)
      return 1
      ;;
  esac
}

if [[ ! -f "$NEW_FILES_MANIFEST" ]]; then
  echo "Generated output missing .openapi-generator/FILES, aborting sync." >&2
  exit 1
fi

# Clean mode: remove files generated by previous run.
if [[ "$CLEAN_REGEN" == "true" ]] && [[ -f "$OLD_FILES_MANIFEST" ]]; then
  while IFS= read -r rel_path; do
    [[ -z "$rel_path" ]] && continue
    if should_skip_generated_path "$rel_path"; then
      continue
    fi
    rm -f "$ROOT_DIR/$rel_path"
  done < "$OLD_FILES_MANIFEST"
fi

# Copy newly generated files to keep structure exactly as generator output.
while IFS= read -r rel_path; do
  [[ -z "$rel_path" ]] && continue
  if should_skip_generated_path "$rel_path"; then
    continue
  fi
  mkdir -p "$ROOT_DIR/$(dirname "$rel_path")"
  cp "$OUTPUT_DIR/$rel_path" "$ROOT_DIR/$rel_path"
done < "$NEW_FILES_MANIFEST"

# In compatibility mode, backfill historical generated files that are not produced now.
if [[ "$COMPAT_RESTORE_MISSING_FROM_HEAD" == "true" ]] && [[ -f "$OLD_FILES_MANIFEST" ]] && command -v git >/dev/null 2>&1; then
  : > "$MISSING_RESTORE_LIST"
  while IFS= read -r rel_path; do
    [[ -z "$rel_path" ]] && continue
    if should_skip_generated_path "$rel_path"; then
      continue
    fi
    if [[ ! -f "$OUTPUT_DIR/$rel_path" ]]; then
      echo "$rel_path" >> "$MISSING_RESTORE_LIST"
    fi
  done < "$OLD_FILES_MANIFEST"

  if [[ -s "$MISSING_RESTORE_LIST" ]]; then
    while IFS= read -r rel_path; do
      if git -C "$ROOT_DIR" cat-file -e "HEAD:$rel_path" 2>/dev/null; then
        mkdir -p "$ROOT_DIR/$(dirname "$rel_path")"
        git -C "$ROOT_DIR" show "HEAD:$rel_path" > "$ROOT_DIR/$rel_path"
      fi
    done < "$MISSING_RESTORE_LIST"
  fi
fi

mkdir -p "$ROOT_DIR/.openapi-generator"
{
  awk 'NF' "$NEW_FILES_MANIFEST"
  if [[ "$COMPAT_RESTORE_MISSING_FROM_HEAD" == "true" ]] && [[ -s "$MISSING_RESTORE_LIST" ]]; then
    cat "$MISSING_RESTORE_LIST"
  fi
} | awk '!seen[$0]++' | while IFS= read -r rel_path; do
  if should_skip_generated_path "$rel_path"; then
    continue
  fi
  echo "$rel_path"
done > "$ROOT_DIR/.openapi-generator/FILES"
cp "$OUTPUT_DIR/.openapi-generator/VERSION" "$ROOT_DIR/.openapi-generator/VERSION"

echo "Generation complete. Project files synchronized to repository layout."
